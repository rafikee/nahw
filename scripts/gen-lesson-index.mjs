#!/usr/bin/env node
/**
 * Regenerate data/index.ts from the lesson files on disk.
 *
 * Lesson data is consumed by client components, so it has to be statically
 * imported and bundled — a filesystem read at runtime would not survive the
 * client boundary. Codegen keeps that constraint while removing the manual
 * "remember to add the import" step, which is the thing that silently breaks
 * as the lesson count grows.
 *
 * Ordering here is irrelevant to the app: data/course.ts decides what the
 * learner sees and in what sequence. This file is only the lookup pool.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = join(ROOT, "data");
const OUT = join(DATA, "index.ts");

const files = readdirSync(DATA)
  .filter((f) => /^lesson_\d+\.json$/.test(f))
  .sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0]));

if (!files.length) {
  console.error("No data/lesson_*.json files found; refusing to write an empty index.");
  process.exit(1);
}

const entries = files.map((file) => {
  const n = file.match(/^lesson_(\d+)\.json$/)[1];
  const doc = JSON.parse(readFileSync(join(DATA, file), "utf8"));
  return { file, ident: `lesson${n}Data`, moduleId: doc.module_id };
});

const body = `// Generated by scripts/gen-lesson-index.mjs — do not edit by hand.
// Run \`npm run gen:lessons\` after adding or removing a lesson file.

import type { Lesson } from "@/types/lesson";
${entries.map((e) => `import ${e.ident} from "./${e.file}";`).join("\n")}

export const LESSONS = [
${entries.map((e) => `  ${e.ident}, // ${e.moduleId}`).join("\n")}
] as unknown as Lesson[];
`;

const previous = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return null;
  }
})();

if (previous === body) {
  console.log(`data/index.ts already current (${entries.length} lessons).`);
} else {
  writeFileSync(OUT, body);
  console.log(`Wrote data/index.ts with ${entries.length} lessons.`);
}
